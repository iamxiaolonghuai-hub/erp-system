CREATE TABLE IF NOT EXISTS finance_actions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 action_no VARCHAR(64) NOT NULL UNIQUE,
 kind VARCHAR(16) NOT NULL,
 account_id BIGINT UNSIGNED NOT NULL,
 target_account_id BIGINT UNSIGNED NULL,
 payment_id BIGINT UNSIGNED NULL,
 source_action_id BIGINT UNSIGNED NULL,
 amount DECIMAL(14,2) NOT NULL,
 pay_method VARCHAR(32) NOT NULL DEFAULT '',
 pay_date DATE NOT NULL,
 remark VARCHAR(255) NOT NULL DEFAULT '',
 status TINYINT NOT NULL DEFAULT 0,
 created_by BIGINT UNSIGNED NOT NULL,
 assigned_approver_id BIGINT UNSIGNED NULL,
 approved_by BIGINT UNSIGNED NULL,
 review_remark VARCHAR(255) NOT NULL DEFAULT '',
 approved_at DATETIME NULL,
 reversed_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_finance_pending(status,created_at), KEY idx_finance_account(account_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
